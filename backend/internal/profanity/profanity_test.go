func TestMask(t *testing.T) {
	cases := map[string]string{
		"ну ты и сука":     "ну ты и с**а",
		"хуевый день":      "х****й день",
		"бля, опять":       "б*я, опять",
		"х.у.й":            "х.*.й",
		"х у й":            "х * й",
		"хорошая новость":  "хорошая новость",
		"pizda и е6ать":    "p***a и е***ь",
		"по-ебански вышло": "по-е*****и вышло",
	}
	for in, want := range cases {
		got, _ := Check(in)
		if got != want {
			t.Errorf("Check(%q) = %q, want %q", in, got, want)
		}
	}
}
